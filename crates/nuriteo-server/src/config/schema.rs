const fn field(
    environment: &'static str,
    file_key: Option<&'static str>,
    value_type: &'static str,
    default_value: Option<&'static str>,
    validation: &'static str,
    helm_mapping: &'static str,
) -> ConfigField {
    ConfigField {
        environment,
        file_key,
        value_type,
        default_value,
        secret: false,
        reloadable: false,
        validation,
        compose_mapping: environment,
        helm_mapping,
    }
}

const fn secret_field(
    environment: &'static str,
    validation: &'static str,
    helm_mapping: &'static str,
) -> ConfigField {
    ConfigField {
        environment,
        file_key: None,
        value_type: "secret",
        default_value: None,
        secret: true,
        reloadable: false,
        validation,
        compose_mapping: environment,
        helm_mapping,
    }
}

