import fs from "node:fs";
import path from "node:path";

const schemaPath = path.resolve("packages/protocol/schema.json");
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));

function magicAsU32(magic) {
  const bytes = new TextEncoder().encode(magic);
  if (bytes.length !== 4) {
    throw new Error("schema magic must be exactly 4 ASCII bytes");
  }
  return bytes[0] | (bytes[1] << 8) | (bytes[2] << 16) | (bytes[3] << 24);
}

function rustName(name) {
  return name.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();
}

function tsObject(entries) {
  return `Object.freeze({\n${Object.entries(entries)
    .map(([name, value]) => `  ${JSON.stringify(name)}: ${value}`)
    .join(",\n")}\n})`;
}

function rustConstants(moduleName, entries, typeName) {
  const constants = Object.entries(entries)
    .map(([name, value]) => `    pub const ${rustName(name)}: ${typeName} = ${value};`)
    .join("\n");
  return `pub mod ${moduleName} {\n${constants}\n}`;
}

const magic = magicAsU32(schema.magic);
const generatedNotice = "This file is generated by tooling/generators/generate-protocol.ts. Do not edit by hand.";

const ts = `// ${generatedNotice}

export const ABI_VERSION = ${schema.abiVersion};
export const MAGIC = 0x${magic.toString(16)};
export const HEADER_LENGTH = ${schema.headerLength};
export const MAX_PAYLOAD_LENGTH = ${schema.maxPayloadLength};

export const STATUS = ${tsObject(schema.status)};

export const OPCODES = ${tsObject(schema.opcodes)};

export const ERROR_CODES = ${tsObject(schema.errors)};

export const GOLDEN_REQUEST = Object.freeze(${JSON.stringify(schema.golden.request, null, 2)});
`;

const rust = `// ${generatedNotice}

pub const ABI_VERSION: u16 = ${schema.abiVersion};
pub const MAGIC: u32 = 0x${magic.toString(16)};
pub const HEADER_LENGTH: usize = ${schema.headerLength};
pub const MAX_PAYLOAD_LENGTH: usize = ${schema.maxPayloadLength};

${rustConstants("status", schema.status, "u16")}

${rustConstants("opcodes", schema.opcodes, "u16")}

${rustConstants("errors", schema.errors, "u16")}

pub const GOLDEN_REQUEST_HEX: &str =
    "${schema.golden.request.wireHex}";
`;

fs.writeFileSync(path.resolve("packages/protocol/src/generated.ts"), ts);
fs.writeFileSync(path.resolve("crates/system-core/src/protocol/generated.rs"), rust);

console.log("protocol generated");
