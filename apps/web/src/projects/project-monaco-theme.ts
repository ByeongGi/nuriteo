export function resolveProjectMonacoTheme(preference: EditorThemePreference): ProjectMonacoTheme {
  if (preference === "stackblitz-dark") return STACKBLITZ_DARK_THEME;
  if (preference === "stackblitz-light") return STACKBLITZ_LIGHT_THEME;
  return prefersDarkEditor() ? STACKBLITZ_DARK_THEME : STACKBLITZ_LIGHT_THEME;
}

function prefersDarkEditor(): boolean {
  if (typeof document !== "undefined") {
    const configuredTheme = document.documentElement.dataset.themeMode;
    if (configuredTheme === "dark") return true;
    if (configuredTheme === "light") return false;
  }
  return typeof globalThis.matchMedia !== "undefined" && globalThis.matchMedia("(prefers-color-scheme: dark)").matches;
}
